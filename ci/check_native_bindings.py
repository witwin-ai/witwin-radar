"""Generate and check the radar native binding manifest.

The operator registrations are the single source of truth: ``m.def`` in
``witwin/radar/cuda/extension.cpp`` declares the schema, ``m.impl`` in one
kernel translation unit implements it, and one production Python module calls
it. Every per-operator column of ``ci/native-binding-manifest.json`` is derived
from those three places. Two sections cannot be derived and are written by
hand: ``no_backward`` (an AD group that is deliberately forward-only, with the
reason) and ``error_owners`` (the module that raises for each failure domain).

    python ci/check_native_bindings.py           check
    python ci/check_native_bindings.py --write   regenerate the derived sections

The check fails when the committed manifest is not what the generator would
write, and on each derived invariant that describes a real defect:

* the declared (``m.def``) and implemented (``m.impl``) operator sets differ,
  or an implementation lives outside the build sources;
* an operator name is not ``<group>_forward``, ``_backward`` or ``_jvp``;
* an AD group lacks its primal, has a backward without a jvp (or the reverse),
  or has neither companion without a ``no_backward`` entry;
* an operator has no production Python caller, or more than one owner module;
* the packaged prebuilt, when present, records a different operator set.
"""

from __future__ import annotations

import argparse
import ast
import json
import re
import sys
from dataclasses import dataclass
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
MANIFEST = REPO_ROOT / "ci" / "native-binding-manifest.json"

# Run as a script, ``sys.path[0]`` is ``ci/``, so ``import witwin.radar`` would
# resolve to whatever is installed in the environment. A gate checks the tree it
# lives in, so this checkout goes first.
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

SCHEMA_VERSION = 3

#: Sections written by hand; the generator carries them over unchanged.
HAND_SECTIONS = ("no_backward", "error_owners")

ROLES = {"_forward": "primal", "_backward": "backward", "_jvp": "jvp"}

ERROR_OWNER_KEYS = frozenset({"domain", "owner_module", "failure_mode"})

COMMENT = [
    "Generated by `python ci/check_native_bindings.py --write` from the m.def",
    "registrations in witwin/radar/cuda/extension.cpp, the m.impl registrations",
    "in the kernel sources, and the production Python modules that call them.",
    "Only no_backward and error_owners are written by hand.",
]

DEFINE = re.compile(r'm\.def\(\s*"(\w+)\(')
IMPLEMENT = re.compile(r'm\.impl\(\s*"(\w+)"')


@dataclass(frozen=True)
class Tree:
    """The inputs the manifest is derived from, read once.

    Tests build a ``Tree`` from edited copies of these texts to show that each
    derived check fires, without writing to the checkout.
    """

    extension: str
    kernels: dict[str, str]
    python: dict[str, str]


def _relative(path: Path) -> str:
    return path.relative_to(REPO_ROOT).as_posix()


def read_tree() -> Tree:
    from witwin.radar.cuda import runtime

    sources = [Path(path).resolve() for path in runtime.extension_sources()]
    extension = next(path for path in sources if path.name == "extension.cpp")
    package = REPO_ROOT / "witwin" / "radar"
    python = {
        _relative(path): path.read_text(encoding="utf-8")
        for path in sorted(package.rglob("*.py"))
        if "__pycache__" not in path.parts and (package / "cuda") not in path.parents
    }
    kernels = {_relative(path): path.read_text(encoding="utf-8") for path in sources if path != extension}
    return Tree(extension.read_text(encoding="utf-8"), kernels, python)


def _attribute_readers(python: dict[str, str]) -> dict[str, dict[str, set[str]]]:
    """``{attribute: {module path: {qualified function}}}`` for every attribute read in ``python``."""

    found: dict[str, dict[str, set[str]]] = {}

    def visit(node: ast.AST, path: str, scope: tuple[str, ...]) -> None:
        for child in ast.iter_child_nodes(node):
            if isinstance(child, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
                visit(child, path, (*scope, child.name))
                continue
            if isinstance(child, ast.Attribute):
                found.setdefault(child.attr, {}).setdefault(path, set()).add(".".join(scope) or "<module>")
            visit(child, path, scope)

    for path, source in python.items():
        visit(ast.parse(source), path, ())
    return found


def derive(tree: Tree, failures: list[str]) -> list[dict]:
    """Every operator row, derived from the registrations and their callers."""

    declared = DEFINE.findall(tree.extension)
    duplicates = sorted({name for name in declared if declared.count(name) > 1})
    if duplicates:
        failures.append(f"extension.cpp declares {duplicates} more than once")
    implemented: dict[str, list[str]] = {}
    for path, text in tree.kernels.items():
        for symbol in IMPLEMENT.findall(text):
            implemented.setdefault(symbol, []).append(path)
    if set(declared) != set(implemented):
        failures.append(
            f"declared and implemented operators differ: only declared {sorted(set(declared) - set(implemented))}, "
            f"only implemented {sorted(set(implemented) - set(declared))}"
        )
    for path in sorted(name for name in tree.kernels if name.endswith(".cu")):
        if path not in {owner for owners in implemented.values() for owner in owners}:
            failures.append(f"build source {path} implements no operator")

    readers = _attribute_readers(tree.python)
    rows = []
    for symbol in sorted(set(declared) | set(implemented)):
        suffix = next((suffix for suffix in ROLES if symbol.endswith(suffix)), None)
        if suffix is None:
            failures.append(f"{symbol}: an operator name ends in _forward, _backward or _jvp")
            continue
        owners = implemented.get(symbol, [])
        if len(owners) > 1:
            failures.append(f"{symbol}: implemented in more than one translation unit {owners}")
        callers = {path: sorted(names) for path, names in readers.get(symbol, {}).items()}
        if not callers:
            failures.append(f"{symbol}: no production Python module calls it")
        elif len(callers) > 1:
            failures.append(f"{symbol}: called from more than one Python owner {sorted(callers)}")
        python_owner = min(callers) if callers else None
        rows.append(
            {
                "symbol": symbol,
                "ad_group": symbol.removesuffix(suffix),
                "ad_role": ROLES[suffix],
                "native_tu": owners[0] if owners else None,
                "python_owner": python_owner,
                "python_callers": callers.get(python_owner, []),
            }
        )
    return rows


def check_ad_groups(rows: list[dict], no_backward: dict, failures: list[str]) -> None:
    """Each group has one primal and both companions, or a declared reason for neither."""

    groups: dict[str, set[str]] = {}
    for row in rows:
        groups.setdefault(row["ad_group"], set()).add(row["ad_role"])
    for group, roles in sorted(groups.items()):
        if "primal" not in roles:
            failures.append(f"ad_group {group!r} has a companion but no _forward primal")
        companions = roles & {"backward", "jvp"}
        if companions == {"backward", "jvp"}:
            if group in no_backward:
                failures.append(f"no_backward names {group!r}, which registers a backward and a jvp")
        elif companions:
            failures.append(f"ad_group {group!r} registers {sorted(companions)} without its other companion")
        elif group not in no_backward:
            failures.append(
                f"ad_group {group!r} registers no backward and no jvp; add the companions, or declare the group "
                "in no_backward with the reason its derivative is refused"
            )
    for group, reason in sorted(no_backward.items()):
        if group not in groups:
            failures.append(f"no_backward names {group!r}, which is not a registered AD group")
        if not isinstance(reason, str) or not reason.strip():
            failures.append(f"no_backward entry {group!r} gives no reason")


def check_error_owners(entries: list, failures: list[str]) -> None:
    domains: set[str] = set()
    for entry in entries:
        if not isinstance(entry, dict) or set(entry) != ERROR_OWNER_KEYS:
            failures.append(f"error_owners entry has wrong keys: {entry}")
            continue
        if entry["domain"] in domains:
            failures.append(f"error_owners: duplicate domain {entry['domain']!r}")
        domains.add(entry["domain"])
        if not (REPO_ROOT / entry["owner_module"]).is_file():
            failures.append(f"error_owners: {entry['owner_module']} does not exist")
        if not str(entry["failure_mode"]).strip():
            failures.append(f"error_owners: {entry['domain']} has an empty failure_mode")


def generate(hand: dict, tree: Tree | None = None, failures: list[str] | None = None) -> dict:
    """The manifest the tree describes, carrying ``hand``'s hand-written sections over."""

    from witwin.radar.cuda import runtime

    failures = [] if failures is None else failures
    tree = read_tree() if tree is None else tree
    rows = derive(tree, failures)
    manifest = {
        "comment": COMMENT,
        "schema_version": SCHEMA_VERSION,
        "radar_abi_version": runtime.RADAR_ABI_VERSION,
        "library": runtime.EXTENSION_NAME,
        "sources": sorted(_relative(Path(path).resolve()) for path in runtime.extension_sources()),
        "no_backward": hand.get("no_backward", {}),
        "error_owners": hand.get("error_owners", []),
        "operators": rows,
    }
    check_ad_groups(rows, manifest["no_backward"], failures)
    check_error_owners(manifest["error_owners"], failures)
    return manifest


def operator_symbols(manifest: dict) -> list[str]:
    return sorted(row["symbol"] for row in manifest["operators"])


def _check_sidecar(manifest: dict, failures: list[str]) -> str:
    """Tie the manifest to the packaged prebuilt, when this checkout has one."""

    from witwin.radar.cuda import runtime

    binary = runtime.prebuilt_extension_path()
    if not binary.is_file():
        return "no packaged prebuilt; symbol-set tie not checked"
    try:
        record = runtime.read_build_info(binary)
    except runtime.RadarExtensionLoadError as error:
        failures.append(f"the packaged prebuilt has no usable build record: {error}")
        return "error"
    recorded, manifested = set(record["operator_symbols"]), set(operator_symbols(manifest))
    if recorded != manifested:
        failures.append(
            "the packaged prebuilt records a different operator set: only in "
            f"binary {sorted(recorded - manifested)}, only in manifest {sorted(manifested - recorded)}"
        )
        return "error"
    return f"symbol-set tie checked against {binary.name} ({len(recorded)} symbols)"


def render(manifest: dict) -> str:
    return json.dumps(manifest, indent=2, ensure_ascii=False) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--manifest", type=Path, default=MANIFEST)
    parser.add_argument("--write", action="store_true", help="regenerate the derived sections in place")
    arguments = parser.parse_args(argv)

    committed_text = arguments.manifest.read_text(encoding="utf-8")
    committed = json.loads(committed_text)
    failures: list[str] = []
    manifest = generate({name: committed.get(name) for name in HAND_SECTIONS if name in committed}, failures=failures)
    if arguments.write:
        arguments.manifest.write_text(render(manifest), encoding="utf-8", newline="\n")
    elif committed_text.replace("\r\n", "\n") != render(manifest):
        failures.append(f"{arguments.manifest.name} is stale; run `python ci/check_native_bindings.py --write`")
    sidecar = _check_sidecar(manifest, failures)
    if failures:
        print("native binding manifest FAILED:")
        for failure in failures:
            print(f"  - {failure}")
        return 1
    groups = {row["ad_group"] for row in manifest["operators"]}
    print(
        f"native binding manifest {'written' if arguments.write else 'OK'}: {len(manifest['operators'])} operators, "
        f"{len(groups)} AD groups, {len(manifest['no_backward'])} forward-only; {sidecar}"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
